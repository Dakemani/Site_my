#!/bin/bash
echo "=== Калькулятор суммы ==="
echo ""
echo -n "Введите первое число: "
read num1
echo -n "Введите второе число: "
read num2
if [ -z "$num1" ] || [ -z "$num2" ]; then
    echo "Ошибка: Оба числа должны быть введены!"
    exit 1
fi
if ! [[ "$num1" =~ ^-?[0-9]+([.][0-9]+)?$ ]] || ! [[ "$num2" =~ ^-?[0-9]+([.][0-9]+)?$ ]]; then
    echo "Ошибка: Пожалуйста, введите корректные числа!"
    exit 1
fi
sum=$(echo "$num1 + $num2" | bc 2>/dev/null || awk "BEGIN {print $num1 + $num2}")
echo ""
echo "========================================"
echo "Результат: $num1 + $num2 = $sum"
echo "========================================"