#!/bin/sh
echo "=== Калькулятор суммы ==="
echo ""
printf "Введите первое число: "
read num1
printf "Введите второе число: "
read num2

if [ -z "$num1" ] || [ -z "$num2" ]; then
    echo "Ошибка: Оба числа должны быть введены!"
    exit 1
fi

# Проверка, что введены числа
if ! echo "$num1" | grep -Eq '^-?[0-9]+(\.[0-9]+)?$' || ! echo "$num2" | grep -Eq '^-?[0-9]+(\.[0-9]+)?$'; then
    echo "Ошибка: Пожалуйста, введите корректные числа!"
    exit 1
fi

# Используем awk для сложения (работает в sh)
result=$(awk "BEGIN {print $num1 + $num2}")
echo ""
echo "========================================"
echo "Результат: $num1 + $num2 = $result"
echo "========================================"